--[[ AutoPort v4 — safe inject / protect hand ports / validate writes. ]]
local M = {}

local MARKER = "pcall(function() require('rmlui.autoport').hijack() end)"
local MARKER_COMMENT = '-- rmlui.autoport: mirror ImGui windows on RmlUi'

function M.read_file(path)
    local f = io.open(path, 'rb')
    if not f then return nil end
    local s = f:read('*a')
    f:close()
    return s
end

function M.write_file(path, data)
    local f = io.open(path, 'wb')
    if not f then return false, 'cannot open for write: ' .. tostring(path) end
    f:write(data)
    f:close()
    return true
end

function M.mkdir(path)
    local win = tostring(path or ''):gsub('/', '\\')
    if win == '' then return end
    os.execute('if not exist "' .. win .. '" mkdir "' .. win .. '"')
end

function M.is_autoport_generated(src)
    if not src or src == '' then return false end
    if src:find('AUTO_PORT_VER=', 1, true) then return true end
    if src:find('-- Generated by AutoPort', 1, true) then return true end
    if src:find("M%.win:text%('status', a%)") then return true end
    if src:find('chip ghost">AutoPort', 1, true) then return true end
    return false
end

--- Hand ports: real rml_ui with tick/ensure and NO AUTO_PORT_VER — never overwrite.
function M.is_hand_port(src)
    if not src then return false end
    if M.is_autoport_generated(src) then return false end
    if src:find('function%s+M%.tick', 1, false) then return true end
    if src:find('function%s+M%.ensure', 1, false) and src:find('host%.open', 1, true) then
        return true
    end
    return false
end

function M.validate_lua(src, name)
    if type(loadstring) == 'function' then
        local fn, err = loadstring(src, name or 'autoport')
        return fn ~= nil, err
    end
    local fn, err = load(src, name or 'autoport', 't', {})
    return fn ~= nil, err
end

function M.validate_rml(rml)
    if not rml or rml == '' then return false, 'empty rml' end
    if not rml:find('<rml', 1, true) then return false, 'missing <rml>' end
    if not rml:find('template="window"', 1, true) then return false, 'missing window template' end
    -- Must have real body content (not just hero + empty status)
    local body = rml:match('<body[^>]*>(.-)</body>')
    if not body or #body < 200 then return false, 'body too thin (empty stub)' end
    if body:find('<style', 1, true) then
        return false, 'style leaked into body (CSS would render as text)'
    end
    local has_ui = body:find('panel', 1, true)
        or body:find('wiki%-split', 1, false)
        or body:find('seg%-item', 1, false)
        or body:find('toolbar', 1, true)
        or body:find('class="btn"', 1, true)
        or body:find("class='btn'", 1, true)
    if not has_ui then return false, 'no interactive UI in body' end
    if body:find('Waiting for API', 1, true) and not has_ui then
        return false, 'refusing Waiting-for-API stub'
    end
    return true
end

function M.strip_hijack(src)
    return src
        :gsub('\r?\n' .. MARKER_COMMENT:gsub('([^%w])', '%%%1'), '')
        :gsub('\r?\n' .. MARKER:gsub('([^%w])', '%%%1'), '')
        :gsub('^' .. MARKER_COMMENT:gsub('([^%w])', '%%%1') .. '\r?\n', '')
        :gsub('^' .. MARKER:gsub('([^%w])', '%%%1') .. '\r?\n', '')
end

--- Replace ONLY the rmlui.board attach block — never greedy across whole file.
function M.strip_board_stub(src)
    -- Only strip AutoPort-injected early-return board attach.
    -- Never rewrite a native `pcall(require, 'rmlui.board')` helper (SmartLoot etc.) —
    -- replacing the call leaves `local ok, board = -- comment` and breaks syntax.
    local next_src, n = src:gsub(
        "if%s+not%s+([%w_]+)%s+then%s*\n%s*local%s+ok%s*,%s*board%s*=%s*pcall%s*%(%s*require%s*,%s*['\"]rmlui%.board['\"]%s*%)%s*\n.-end%s*\n%s*if%s+%1%s+then%s+%1%.tick%s*%(%s*%)%s*;%s*return%s+end",
        "if rml_ui then rml_ui.tick(); return end",
        1)
    if n > 0 then return next_src end
    return src
end

function M.ensure_use_rml(src, on)
    if on then
        local next_src, n = src:gsub('local USE_RML%s*=%s*false', 'local USE_RML = true', 1)
        if n > 0 then return next_src end
        next_src, n = src:gsub('USE_RML%s*=%s*false', 'USE_RML = true', 1)
        if n > 0 then return next_src end
        if not src:find('USE_RML', 1, true) then
            return 'local USE_RML = true\n' .. src
        end
        return src
    end
    local next_src, n = src:gsub('local USE_RML%s*=%s*true', 'local USE_RML = false', 1)
    if n > 0 then return next_src end
    next_src, n = src:gsub('USE_RML%s*=%s*true', 'USE_RML = false', 1)
    return next_src
end

function M.inject_require(src, require_path, label)
    if src:find("require%s*%(?['\"]" .. require_path:gsub('([^%w])', '%%%1'), 1, false) then
        return src
    end
    local block = string.format(
        "local rml_ui = nil\nif USE_RML then\n    local ok, mod = pcall(require, '%s')\n    if ok then rml_ui = mod else USE_RML = false print('[%s] Rml fallback: ' .. tostring(mod)) end\nend\n",
        require_path, label)
    if src:find('local rml_ui%s*=', 1, false) then return src end
    if src:find('local USE_RML', 1, true) then
        return src:gsub('(local USE_RML[^\n]*\n)', '%1' .. block, 1)
    end
    local patched, n = src:gsub(
        "([^\r\n]*require%s*%(?['\"]mq['\"]%)?[^\r\n]*\n)",
        '%1local USE_RML = true\n' .. block, 1)
    if n > 0 then return patched end
    return 'local USE_RML = true\n' .. block .. src
end

--- Plain find for rml_ui.tick — never escape dots when plain=true.
--- Only strip broken tick(nil)/RmlAPI early-returns that never reach a real API.
--- Keep valid `rml_ui.tick(); return` (structure ports) and `rml_ui.tick(SomeAPI)`.
function M.inject_tick(src)
    if src:find('rml_ui.tick', 1, true) then
        local cleaned = src
        -- Dead pattern: tick(type(RmlAPI)=='table' and RmlAPI or nil) then return
        cleaned = cleaned:gsub(
            "\r?\n%s*if%s+USE_RML%s+and%s+rml_ui%s+then%s*\r?\n%s*rml_ui%.tick%s*%(%s*type%s*%(%s*RmlAPI%s*%)%s*==%s*'table'%s+and%s+RmlAPI%s+or%s+nil%s*%)%s*\r?\n%s*return%s*\r?\n%s*end%s*",
            '\n')
        -- Dead pattern: tick(nil) then return
        cleaned = cleaned:gsub(
            '\r?\n%s*if%s+USE_RML%s+and%s+rml_ui%s+then%s*\r?\n%s*rml_ui%.tick%s*%(%s*nil%s*%)%s*\r?\n%s*return%s*\r?\n%s*end%s*',
            '\n')
        return cleaned
    end
    local body = "    if USE_RML and rml_ui then\n        rml_ui.tick()\n        return\n    end\n"
    local patched, n = src:gsub(
        '(mq%.imgui%.init%s*%(%s*[\'"][^\'"]+[\'"]%s*,%s*function%s*%([^%)]*%)%s*\n)',
        '%1' .. body, 1)
    if n > 0 then return patched end
    patched, n = src:gsub(
        '(mq%.imgui%.init%s*%(%s*[%w_%.]+%s*,%s*function%s*%([^%)]*%)%s*\n)',
        '%1' .. body, 1)
    if n > 0 then return patched end
    patched, n = src:gsub(
        '(ImGui%.Register%s*%(%s*[\'"][^\'"]+[\'"]%s*,%s*function%s*%([^%)]*%)%s*\n)',
        '%1' .. body, 1)
    if n > 0 then return patched end
    patched, n = src:gsub(
        '(ImGui%.Register%s*%(%s*[%w_%.]+%s*,%s*function%s*%([^%)]*%)%s*\n)',
        '%1' .. body, 1)
    if n > 0 then return patched end
    return src
end

function M.safe_write_lua(path, src)
    local ok, err = M.validate_lua(src, path)
    if not ok then return false, 'lua syntax: ' .. tostring(err) end
    return M.write_file(path, src)
end

function M.safe_write_rml(path, rml)
    local ok, err = M.validate_rml(rml)
    if not ok then return false, 'rml validate: ' .. tostring(err) end
    return M.write_file(path, rml)
end

return M
